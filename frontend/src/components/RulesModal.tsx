function scrollToSection(id: string) {
  document.getElementById(`rules-${id}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' })
}

function RuleCard({ item }: { item: RuleItem }) {
  return (
    <div className="rounded-2xl bg-white/70 border border-pink-soft/35 p-4 shadow-sm">
      <div className="flex items-start gap-2">
        {item.num && <span className="text-pink font-bold text-sm shrink-0">{item.num}</span>}
        <div className="min-w-0 flex-1">
          {item.title && <div className="font-semibold text-sm text-ink/85 mb-1">{item.title}</div>}
          {item.body?.map((text, i) => (
            <p key={i} className="text-sm text-ink/65 leading-relaxed mb-2 last:mb-0">{text}</p>
          ))}
          {item.bullets && (
            <ul className="mt-2 space-y-1.5 text-sm text-ink/65 leading-relaxed">
              {item.bullets.map((text, i) => (
                <li key={i} className="flex gap-2">
                  <span className="mt-2 h-1.5 w-1.5 rounded-full bg-pink/70 shrink-0" />
                  <span>{text}</span>
                </li>
              ))}
            </ul>
          )}
          {item.punishment && (
            <div className="mt-3 rounded-xl bg-pink-soft/25 px-3 py-2 text-xs sm:text-sm text-ink/65">
              <span className="font-semibold text-pink-deep">Наказание:</span> {item.punishment}
            </div>
          )}
        </div>
      </div>
    </div>
  )
}

